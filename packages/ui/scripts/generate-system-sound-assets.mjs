// 生成系统提示音的静态资源表（systemSoundAssets.generated.ts）。
//
// 背景：936 个 mp3（12 包 ×78）手写 import 要 936 行，改不动也审不动。
// 所以 catalog 只手写类型与语义，这个文件由本脚本从 assets 目录扫描生成。
// 音源与 instant-app 的 uisfx 目录同名，新增风格包只需拷目录后重跑本脚本。
//
// 用法：node packages/ui/scripts/generate-system-sound-assets.mjs
// 输出：packages/ui/src/lib/systemSoundAssets.generated.ts（需提交入库）

import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const assetsDir = join(here, "..", "src", "assets", "system-sounds");
const outFile = join(here, "..", "src", "lib", "systemSoundAssets.generated.ts");

function toIdentifier(value) {
  return value.replace(/[^a-zA-Z0-9_]/g, "_");
}

const packs = readdirSync(assetsDir, { withFileTypes: true })
  .filter((entry) => entry.isDirectory() && entry.name !== "licenses" && !entry.name.startsWith("."))
  .map((entry) => entry.name)
  .sort();

const cuesByPack = new Map();
for (const pack of packs) {
  const cues = readdirSync(join(assetsDir, pack))
    .filter((name) => name.endsWith(".mp3"))
    .map((name) => name.slice(0, -".mp3".length))
    .sort();
  cuesByPack.set(pack, cues);
}

const lines = [];
lines.push("/* eslint-disable max-lines -- 936 个 mp3 的静态资源表由脚本生成，手写 import 要 936 行；类型与语义在 systemSoundCatalog.ts 维护。 */");
lines.push("// @generated by packages/ui/scripts/generate-system-sound-assets.mjs");
lines.push("// 手改会被覆盖：改类型与语义去 systemSoundCatalog.ts，加音源后重跑本脚本。");
for (const pack of packs) {
  for (const cue of cuesByPack.get(pack)) {
    const name = `${toIdentifier(pack)}_${toIdentifier(cue)}_Url`;
    lines.push(`import ${name} from "@/assets/system-sounds/${pack}/${cue}.mp3";`);
  }
}
lines.push("");
lines.push("export const GENERATED_SOUND_ASSET_URLS: Record<string, Record<string, string>> = {");
for (const pack of packs) {
  lines.push(`  ${JSON.stringify(pack)}: {`);
  for (const cue of cuesByPack.get(pack)) {
    const name = `${toIdentifier(pack)}_${toIdentifier(cue)}_Url`;
    lines.push(`    ${JSON.stringify(cue)}: ${name},`);
  }
  lines.push("  },");
}
lines.push("};");
lines.push("");

writeFileSync(outFile, `${lines.join("\n")}`);
console.log(
  `[system-sounds] ${packs.length} packs, ${[...cuesByPack.values()].reduce((n, cues) => n + cues.length, 0)} files -> ${outFile}`,
);
