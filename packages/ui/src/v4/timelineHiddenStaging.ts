// 暗处暂存区的定位契约：首绘 staging 区与前插块 staged 容器共用同一份类名。
//
// 为什么不能用固定负偏移（`top: -10000px` 这类）：偏移量是常量，内容比它高时，块的下
// 半截会落回容器上沿以下——画进可见区盖住真实消息，同时向下溢出会进 scrollHeight，把
// 虚拟列表的坐标基准整个污染掉。超长回合（单轮几万 px）在窄屏上很常见，「加载很久时
// 消息重叠错位」就是这么来的。
//
// 为什么不用 JS 先量高度再搬走：测量要求内容已经排版，而排版要求块先在文档里；先渲染
// 再搬运，中间必有一帧文字露进可视区。这里让 CSS 自己算——`bottom: 100%` 把块的底边
// 对齐容器上沿，内容越长就往上延伸越多，不需要提前知道高度。
//
// `visibility: hidden` 保留布局与真实高度（`getBoundingClientRect` 仍返回真实盒），只是
// 不绘制：量得到、看不见在首帧就成立，不需要「量完再隐藏」的中间态。注意它不是
// `display: none`——后者会让高度归零，测量直接失效。
//
// 隐藏与定位必须同时生效：任何一帧里暗处内容都不得画进可见区。

/**
 * 暗处暂存区的定位类。
 *
 * - `absolute`：脱离文档流，`bottom` 才有意义；否则块会进流，把高度算进容器。
 * - `bottom-full`：`bottom: 100%`，底边对齐容器上沿，内容向上延伸。
 * - `invisible`：`visibility: hidden`，保留布局与真实高度，不绘制。
 */
export const HIDDEN_TIMELINE_STAGING_CLASS_NAME = "invisible absolute bottom-full";
